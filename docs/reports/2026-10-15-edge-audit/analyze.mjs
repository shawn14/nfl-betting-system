import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { americanToDecimal, impliedProb, devigTwoWay, logLoss, brier } from '../../../src/lib/fair-value.ts';
import { evaluateGame } from '../../../src/lib/ev-model.ts';
const DIR=path.dirname(fileURLToPath(import.meta.url));
const read=f=>JSON.parse(fs.readFileSync(`${DIR}/${f}.json`,'utf8'));
const mean=a=>a.reduce((s,x)=>s+x,0)/a.length;
const sd=a=>Math.sqrt(a.reduce((s,x)=>s+(x-mean(a))**2,0)/(a.length-1));
const r=x=>Number.isFinite(x)?+x.toFixed(6):null;
function wilson(w,l){const n=w+l,z=1.96,p=w/n,d=1+z*z/n,c=(p+z*z/(2*n))/d,h=z*Math.sqrt(p*(1-p)/n+z*z/(4*n*n))/d;return [r(c-h),r(c+h)];}
function summary(b){const w=b.filter(x=>x.profit>0).length,l=b.filter(x=>x.profit<0).length,p=b.length-w-l,profits=b.map(x=>x.profit),se=sd(profits)/Math.sqrt(b.length);return {n:b.length,w,l,p,winPct:r(w/(w+l)),winCI95:wilson(w,l),units:r(profits.reduce((s,x)=>s+x,0)),roi:r(mean(profits)),roiCI95:[r(mean(profits)-1.96*se),r(mean(profits)+1.96*se)]};}
const profit=(y,price)=>y===0?0:y>0?americanToDecimal(price)-1:-1;
const high=(s,k,x)=>s==='nhl'?x.isHighConviction:k==='ml'?Math.abs(x.homeWinProb-.5)>=.15:k==='total'?Math.abs(x.predictedTotal-x.vegasTotal)>=7:s==='wnba'?x.conviction?.isHighConviction===true:Math.abs(x.predictedSpread-x.vegasSpread)>=2;
const out={generated:new Date().toISOString(),warning:'Stored model predictions are generated by the final-game grading job; no prospective profitability claim is valid from these rows.',sports:{}};
for(const sport of ['nfl','wnba','nhl']){
 const blob=read(sport),rows=blob.backtest.results,px=read(`${sport}-prices`),scopes={all:rows,frozen:rows.filter(x=>x.modelVersion),postEv:rows.filter(x=>x.modelVersion&&x.gameTime>='2026-09-27')};
 out.sports[sport]={generated:blob.generated,rows:rows.length,duplicates:rows.length-new Set(rows.map(x=>x.gameId)).size,scopes:{}};
 for(const [scope,rr] of Object.entries(scopes)){
  const v={n:rr.length,from:rr.map(x=>x.gameTime).sort()[0],to:rr.map(x=>x.gameTime).sort().at(-1),markets:{}};
  for(const mk of ['spread','total','ml']){
   const key=mk==='spread'?'atsResult':mk==='ml'?'mlResult':sport==='nhl'?'ouResult':'ouVegasResult';
   const score=(list)=>{const c={win:0,loss:0,push:0,missing:0};for(const x of list)c[x[key]||'missing']++;return {...c,rate:r(c.win/(c.win+c.loss)),ci95:wilson(c.win,c.loss)};};
   const all=[],hc=[],sameLine=[];
   for(const x of rr){
    const c=px[x.gameId]?.close;if(!c)continue;
    const margin=x.actualHomeScore-x.actualAwayScore,total=x.actualHomeScore+x.actualAwayScore;
    let side,y,price,match;
    if(mk==='ml'){
     const p=sport==='nhl'?x.homeWinProb/100:x.homeWinProb;
     side=x.mlPick?x.mlPick==='home':p>.5;price=side?c.mlHome:c.mlAway;y=margin===0?0:side===(margin>0)?1:-1;match=true;
    }else if(mk==='spread'){
     if(x.predictedSpread===c.spreadLine)continue;
     side=x.predictedSpread<c.spreadLine;price=side?c.spreadHomePrice:c.spreadAwayPrice;
     y=margin+c.spreadLine===0?0:side===(margin+c.spreadLine>0)?1:-1;match=c.spreadLine===x.vegasSpread;
    }else{
     if(x.predictedTotal===c.totalLine)continue;
     side=x.predictedTotal>c.totalLine;price=side?c.overPrice:c.underPrice;
     y=total===c.totalLine?0:side===(total>c.totalLine)?1:-1;match=c.totalLine===x.vegasTotal;
    }
    if(!Number.isFinite(price))continue;
    const b={id:x.gameId,profit:profit(y,price),price};all.push(b);if(high(sport,mk,x))hc.push(b);if(match)sameLine.push(b);
   }
   v.markets[mk]={stored:score(rr),storedHighConviction:score(rr.filter(x=>high(sport,mk,x))),reconstructedClose:summary(all),highConvictionRepriced:summary(hc),sameLineClose:summary(sameLine)};
  }
  const probs=[];
  for(const x of rr){const c=px[x.gameId]?.close;if(!c||!c.mlHome||!c.mlAway||x.actualHomeScore===x.actualAwayScore)continue;const p=sport==='nhl'?x.homeWinProb/100:x.homeWinProb,market=devigTwoWay(c.mlHome,c.mlAway,'power'),y=x.actualHomeScore>x.actualAwayScore?1:0;probs.push({p,market,y,price:market>.5?c.mlHome:c.mlAway});}
  v.moneylineCalibration={n:probs.length,modelBrier:r(mean(probs.map(x=>brier(x.p,x.y)))),marketBrier:r(mean(probs.map(x=>brier(x.market,x.y)))),modelLogLoss:r(mean(probs.map(x=>logLoss(x.p,x.y)))),marketLogLoss:r(mean(probs.map(x=>logLoss(x.market,x.y)))),marketFavorite:summary(probs.map(x=>({profit:profit((x.market>.5)===(x.y===1)?1:-1,x.price)})))};
  if(sport==='nfl'){
   const bets=[];
   for(const x of rr){const c=px[x.gameId]?.close;if(!c)continue;const ev=evaluateGame('nfl',x.homeTeam,x.awayTeam,{homeWinProbability:x.homeWinProb,predictedSpread:x.predictedSpread,predictedTotal:x.predictedTotal},c);const b=ev.markets.find(m=>m.market==='total')?.best;if(!b)continue;const y=x.actualTotal===c.totalLine?0:(b.label.startsWith('Over'))===(x.actualTotal>c.totalLine)?1:-1;bets.push({id:x.gameId,gameTime:x.gameTime,label:b.label,price:b.price,ev:b.ev,profit:profit(y,b.price)});}
   v.fixedEvRule={...summary(bets),bets};
  }
  out.sports[sport].scopes[scope]=v;
 }
}
const ledger=read('shop-ledger'),now=Date.parse(ledger.updated);
const started=ledger.entries.filter(e=>Date.parse(e.commence)<=now);
function clvSummary(entries){
 const a=entries.map(e=>({...e,clv:e.closeFair-impliedProb(e.price)}));
 const vals=a.map(x=>x.clv),m=mean(vals),se=sd(vals)/Math.sqrt(vals.length),groups=new Map();
 for(const e of a){const k=e.eventId;if(!groups.has(k))groups.set(k,[]);groups.get(k).push(e.clv);}
 const G=groups.size,n=vals.length,clusterSe=Math.sqrt(G/(G-1)*[...groups.values()].reduce((s,v)=>s+v.reduce((t,x)=>t+x-m,0)**2,0)/(n*n));
 return {n,G,mean:r(m),se:r(se),naiveCI95:[r(m-1.96*se),r(m+1.96*se)],clusterSe:r(clusterSe),clusterCI95:[r(m-1.96*clusterSe),r(m+1.96*clusterSe)],positive:a.filter(x=>x.clv>0).length,impliedCloseROI:r(mean(a.map(e=>e.closeFair*americanToDecimal(e.price)-1)))};
}
const closed=started.filter(e=>e.closeFair!=null),valid=closed.filter(e=>Date.parse(e.closeAt)>Date.parse(e.flaggedAt)&&Date.parse(e.closeAt)<Date.parse(e.commence)),fresh=valid.filter(e=>Date.parse(e.commence)-Date.parse(e.closeAt)<=3600000);
out.shop={updated:ledger.updated,entries:ledger.entries.length,started:started.length,graded:closed.length,sameSnapshot:closed.filter(e=>e.flaggedAt===e.closeAt).length,staleOverHour:closed.filter(e=>Date.parse(e.commence)-Date.parse(e.closeAt)>3600000).length,all:clvSummary(closed),laterOnly:clvSummary(valid),laterWithinHour:clvSummary(fresh),bySport:Object.fromEntries(['nfl','wnba','nhl'].map(s=>[s,{all:clvSummary(closed.filter(x=>x.sport===s)),strict:clvSummary(fresh.filter(x=>x.sport===s))}]))};
const settled=[],unmatched=[];
for(const e of started){
 const d=read(e.sport);const names=new Map(d.teams.map(x=>[x.name,x.abbreviation]));
 const [away,home]=e.matchup.split(' @ ');const rows=d.backtest.results;
 const x=rows.find(x=>x.homeTeam===names.get(home)&&x.awayTeam===names.get(away)&&Math.abs(Date.parse(x.gameTime)-Date.parse(e.commence))<3600000);
 if(!x){unmatched.push(e.key);continue;}
 const margin=x.actualHomeScore-x.actualAwayScore,total=x.actualHomeScore+x.actualAwayScore;
 let v;
 if(e.market==='ml'){const h=e.label.startsWith(home);v=(h?margin:-margin);}
 else if(e.market==='total'){v=(e.label.toLowerCase().startsWith('over')?1:-1)*(total-e.line);}
 else{const h=e.label.startsWith(home),line=Number(e.label.match(/([+-]?\d+(?:\.\d+)?)$/)?.[1]);v=(h?margin:-margin)+line;}
 settled.push({...e,gameId:x.gameId,profit:profit(v,e.price)});
}
